import React, { useEffect, useMemo, useState } from "react";
import { Download, Pause, Play } from "lucide-react";
import type { TrackedEntity, VideoTelemetry } from "../api/types";

// The radar is a pure view over telemetry the worker already persisted. It does
// no fetching and no uploading: the page owns the data, which is what makes the
// "simulated" provenance below impossible to lose in transit.

const VIEW_W = 800;
const VIEW_H = 500;
const PAD = 24;

const ROLE_COLORS: Array<[string, string]> = [
  ["attacker", "#FF334B"], // vector-crimson
  ["defender", "#06B6D4"], // vector-cyan
  ["midfield", "#CCFF00"], // volt
  ["pivot", "#CCFF00"],
  ["post", "#CCFF00"],
  ["ball", "#F59E0B"], // vector-amber
];

function entityColor(role: string): string {
  const lower = role.toLowerCase();
  const hit = ROLE_COLORS.find(([needle]) => lower.includes(needle));
  return hit ? hit[1] : "#A1A1AA";
}

const isBall = (entity: TrackedEntity) => entity.role.toLowerCase().includes("ball");

const clamp = (value: number, lo: number, hi: number) =>
  Math.min(Math.max(value, lo), hi);

interface EntityTotals {
  id: string;
  label: string;
  role: string;
  peakSpeed: number;
  distance: number;
}

export interface TacticalRadarProps {
  telemetry: VideoTelemetry;
  /** Source clip name, shown in the header and the exported report. */
  filename?: string;
}

export const TacticalRadar: React.FC<TacticalRadarProps> = ({
  telemetry,
  filename,
}) => {
  const [frameIdx, setFrameIdx] = useState(0);
  const [isPlaying, setIsPlaying] = useState(false);

  const frames = useMemo(() => telemetry.frames ?? [], [telemetry.frames]);
  const simulated = telemetry.source === "simulated";
  const sport = telemetry.sport ?? "football";
  const surface = telemetry.surface;

  // A new clip restarts playback rather than inheriting the old index.
  useEffect(() => {
    setFrameIdx(0);
    setIsPlaying(false);
  }, [telemetry]);

  // Step the animation at the clip's own sample spacing, so playback runs at
  // roughly real time instead of a fixed 500 ms the data never agreed to.
  const stepMs = useMemo(() => {
    if (frames.length < 2) return 400;
    const span =
      frames[frames.length - 1].timestamp_sec - frames[0].timestamp_sec;
    if (span <= 0) return 400;
    return clamp((span / (frames.length - 1)) * 1000, 80, 1000);
  }, [frames]);

  useEffect(() => {
    if (!isPlaying || frames.length < 2) return;
    const timer = setInterval(
      () => setFrameIdx((prev) => (prev + 1) % frames.length),
      stepMs,
    );
    return () => clearInterval(timer);
  }, [isPlaying, frames.length, stepMs]);

  // distance_covered_m is cumulative, so its maximum is its final value.
  const totals = useMemo<EntityTotals[]>(() => {
    const acc = new Map<string, EntityTotals>();
    for (const frame of frames) {
      for (const entity of frame.tracked_entities) {
        const current =
          acc.get(entity.id) ??
          {
            id: entity.id,
            label: entity.label,
            role: entity.role,
            peakSpeed: 0,
            distance: 0,
          };
        current.peakSpeed = Math.max(current.peakSpeed, entity.speed_mps);
        current.distance = Math.max(current.distance, entity.distance_covered_m);
        acc.set(entity.id, current);
      }
    }
    return [...acc.values()];
  }, [frames]);

  if (frames.length === 0) {
    return (
      <div className="rounded-xl border border-pitch-border bg-pitch-card p-4 font-mono text-xs text-zinc-400">
        This clip has no telemetry frames.
      </div>
    );
  }

  const frame = frames[Math.min(frameIdx, frames.length - 1)];
  const duration =
    telemetry.duration_sec || frames[frames.length - 1].timestamp_sec;

  // Map the clip's pixel space onto the radar. Falling back to the viewBox
  // keeps a clip with unreadable dimensions from collapsing into one corner.
  const frameW = telemetry.frame_width > 0 ? telemetry.frame_width : VIEW_W;
  const frameH = telemetry.frame_height > 0 ? telemetry.frame_height : VIEW_H;
  const sx = (x: number) =>
    clamp(PAD + (x / frameW) * (VIEW_W - 2 * PAD), PAD, VIEW_W - PAD);
  const sy = (y: number) =>
    clamp(PAD + (y / frameH) * (VIEW_H - 2 * PAD), PAD, VIEW_H - PAD);

  const outfield = frame.tracked_entities.filter((e) => !isBall(e));
  const attacker = frame.tracked_entities.find((e) =>
    e.role.toLowerCase().includes("attacker"),
  );
  const defender = frame.tracked_entities.find((e) =>
    e.role.toLowerCase().includes("defender"),
  );
  const ball = frame.tracked_entities.find(isBall);

  const exportReport = () => {
    const provenance = simulated
      ? "SIMULATED — generated by a kinematic model, not measured from this footage."
      : `Source: ${telemetry.source}`;

    const body = [
      `# Tactical Telemetry Report`,
      ``,
      `Clip: ${filename ?? "(unnamed)"}`,
      `Sport: ${sport}`,
      `Duration: ${duration.toFixed(1)}s across ${frames.length} sampled keyframes`,
      `Provenance: ${provenance}`,
      ...(surface
        ? [
            `Scale assumption: ${surface.assumption} `
              + `(${surface.length_m}m x ${surface.width_m}m)`,
          ]
        : []),
      ``,
      `## Summary`,
      ``,
      telemetry.tactical_summary,
      ``,
      `## Per-entity metrics`,
      ``,
      ...totals
        .filter((t) => !t.role.toLowerCase().includes("ball"))
        .map(
          (t) =>
            `### ${t.label} (${t.role})\n`
            + `- Distance covered: ${t.distance.toFixed(1)} m\n`
            + `- Peak speed: ${t.peakSpeed.toFixed(1)} m/s`,
        ),
      ``,
    ].join("\n");

    const blob = new Blob([body], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    const stem = (filename ?? "clip").replace(/[^a-zA-Z0-9._-]+/g, "_");
    link.href = url;
    link.setAttribute("download", `telemetry_report_${stem}.md`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="flex w-full flex-col gap-4 rounded-xl border border-pitch-border bg-pitch-card p-5 text-zinc-100 shadow-xl">
      {/* Header */}
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-pitch-border pb-3">
        <div>
          <div className="flex items-center gap-2">
            <h2 className="text-sm font-bold tracking-wide text-white">
              {sport.toUpperCase()} RADAR
              {filename ? <span className="text-zinc-500"> / {filename}</span> : null}
            </h2>
            <span
              className={`rounded border px-2 py-0.5 font-mono text-[10px] uppercase ${
                simulated
                  ? "border-vector-amber/40 bg-vector-amber/10 text-vector-amber"
                  : "border-volt/30 bg-volt/10 text-volt"
              }`}
              title={
                simulated
                  ? "Trajectories come from a kinematic model, not from tracking this clip."
                  : `Telemetry source: ${telemetry.source}`
              }
            >
              {simulated ? "Simulated" : telemetry.source}
            </span>
          </div>
          <p className="mt-0.5 font-mono text-xs text-zinc-400">
            t=
            <span className="font-semibold text-volt">
              {frame.timestamp_sec.toFixed(1)}s
            </span>
            {duration > 0 ? ` / ${duration.toFixed(1)}s` : null}
            <span className="text-zinc-600"> · frame {frame.frame_index}</span>
          </p>
        </div>

        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={exportReport}
            className="flex cursor-pointer items-center gap-1.5 rounded border border-pitch-border bg-pitch-dark px-3 py-1.5 font-mono text-xs font-semibold text-zinc-300 transition-colors hover:text-white"
          >
            <Download className="h-3.5 w-3.5 text-vector-cyan" />
            <span>Export (.md)</span>
          </button>

          <button
            type="button"
            onClick={() => setIsPlaying((p) => !p)}
            disabled={frames.length < 2}
            className="flex cursor-pointer items-center gap-1 rounded bg-volt px-3 py-1.5 font-mono text-xs font-semibold text-pitch-dark transition-colors hover:bg-volt-dim disabled:opacity-40"
          >
            {isPlaying ? (
              <Pause className="h-3.5 w-3.5" />
            ) : (
              <Play className="h-3.5 w-3.5" />
            )}
            <span>{isPlaying ? "Pause" : "Play"}</span>
          </button>

          <input
            type="range"
            min={0}
            max={frames.length - 1}
            value={Math.min(frameIdx, frames.length - 1)}
            aria-label="Scrub keyframes"
            onChange={(e) => {
              setIsPlaying(false);
              setFrameIdx(Number(e.target.value));
            }}
            className="w-32 cursor-pointer accent-volt"
          />
        </div>
      </div>

      {/* Surface */}
      <div className="relative w-full overflow-hidden rounded-lg border border-pitch-border bg-pitch-dark">
        <svg
          viewBox={`0 0 ${VIEW_W} ${VIEW_H}`}
          className="h-auto w-full select-none"
          role="img"
          aria-label={`${sport} radar at ${frame.timestamp_sec.toFixed(1)} seconds`}
        >
          <SurfaceMarkings sport={sport} />

          {/* Defender → attacker cover line */}
          {defender && attacker ? (
            <line
              x1={sx(defender.coordinates.x)}
              y1={sy(defender.coordinates.y)}
              x2={sx(attacker.coordinates.x)}
              y2={sy(attacker.coordinates.y)}
              stroke="#06B6D4"
              strokeWidth={1.5}
              strokeDasharray="4 4"
            />
          ) : null}

          {/* Defender → ball line */}
          {defender && ball ? (
            <line
              x1={sx(defender.coordinates.x)}
              y1={sy(defender.coordinates.y)}
              x2={sx(ball.coordinates.x)}
              y2={sy(ball.coordinates.y)}
              stroke="#F59E0B"
              strokeWidth={1.25}
              strokeDasharray="3 3"
            />
          ) : null}

          {frame.tracked_entities.map((entity) => {
            const px = sx(entity.coordinates.x);
            const py = sy(entity.coordinates.y);
            const color = entity.color ?? entityColor(entity.role);
            const ballMark = isBall(entity);

            return (
              <g key={entity.id}>
                <circle
                  cx={px}
                  cy={py}
                  r={ballMark ? 8 : 15}
                  fill={color}
                  fillOpacity={0.22}
                />
                <circle
                  cx={px}
                  cy={py}
                  r={ballMark ? 4.5 : 8.5}
                  fill={color}
                  stroke="#080A08"
                  strokeWidth={1.5}
                />
                <text
                  x={px}
                  y={py - (ballMark ? 12 : 18)}
                  textAnchor="middle"
                  fill="#F4F4F5"
                  fontSize={11}
                  fontWeight={600}
                >
                  {entity.label}
                </text>
                {!ballMark ? (
                  <text
                    x={px}
                    y={py + 25}
                    textAnchor="middle"
                    fill="#06B6D4"
                    fontSize={9.5}
                    fontFamily="monospace"
                    fontWeight={700}
                  >
                    {entity.speed_mps.toFixed(1)} m/s
                  </text>
                ) : null}
              </g>
            );
          })}
        </svg>
      </div>

      {/* Per-entity strip, current frame */}
      <div className="grid grid-cols-2 gap-3 md:grid-cols-3">
        {outfield.map((entity) => (
          <div
            key={entity.id}
            className="rounded-lg border border-pitch-border bg-pitch-dark p-2.5"
          >
            <span className="block font-mono text-[10px] uppercase text-zinc-500">
              {entity.label}
            </span>
            <div className="mt-1 flex items-baseline justify-between font-mono">
              <span className="text-sm font-bold text-white">
                {entity.speed_mps.toFixed(1)} m/s
              </span>
              <span className="text-xs text-volt">
                {entity.distance_covered_m.toFixed(1)} m
              </span>
            </div>
          </div>
        ))}
      </div>

      {/* Summary + provenance */}
      <div className="rounded-lg border border-pitch-border bg-pitch-dark p-3">
        <p className="mb-1 font-mono text-[11px] font-semibold uppercase tracking-wider text-volt">
          Tactical breakdown
        </p>
        <p className="whitespace-pre-line text-xs leading-relaxed text-zinc-300">
          {telemetry.tactical_summary}
        </p>
        {surface ? (
          <p className="mt-2 border-t border-pitch-border pt-2 font-mono text-[10px] text-zinc-500">
            Scale: {surface.assumption} ({surface.length_m}m × {surface.width_m}m).
          </p>
        ) : null}
      </div>
    </div>
  );
};

/** Pitch or court markings. Decorative — nothing is measured off these. */
const SurfaceMarkings: React.FC<{ sport: string }> = ({ sport }) => {
  const stroke = "#CCFF00";
  const common = { fill: "none", stroke, strokeWidth: 2, strokeOpacity: 0.28 };

  if (sport === "basketball") {
    return (
      <g>
        <rect x={20} y={20} width={760} height={460} {...common} />
        <line x1={400} y1={20} x2={400} y2={480} {...common} />
        <circle cx={400} cy={250} r={55} {...common} />
        {/* Keys */}
        <rect x={20} y={160} width={150} height={180} {...common} />
        <rect x={630} y={160} width={150} height={180} {...common} />
        {/* Three-point arcs */}
        <path d="M 20 90 A 210 210 0 0 1 20 410" {...common} />
        <path d="M 780 90 A 210 210 0 0 0 780 410" {...common} />
      </g>
    );
  }

  return (
    <g>
      <rect x={20} y={20} width={760} height={460} {...common} />
      <line x1={400} y1={20} x2={400} y2={480} {...common} />
      <circle cx={400} cy={250} r={60} {...common} />
      <circle cx={400} cy={250} r={3} fill={stroke} fillOpacity={0.5} stroke="none" />
      {/* Penalty areas */}
      <rect x={20} y={130} width={120} height={240} {...common} />
      <rect x={660} y={130} width={120} height={240} {...common} />
      {/* Six-yard boxes */}
      <rect x={20} y={190} width={48} height={120} {...common} />
      <rect x={732} y={190} width={48} height={120} {...common} />
    </g>
  );
};

export default TacticalRadar;
